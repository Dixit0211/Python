# using for & range

#print numbers from 1 to 100.
for i in range(1,101):
    print(i)

#print the number from 100 to 1
for j in range(100,0,-1): # decrese the number by 1
    print(j)

# print the mutiplication table of a number n.
n = int(input("Enter the number:"))

for k in range(1,11):
    print(n*k)